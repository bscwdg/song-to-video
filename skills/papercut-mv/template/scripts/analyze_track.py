#!/usr/bin/env python3
"""Measure a song, snap cuts to its beat grid, and emit a Remotion timeline.

Examples:
  python analyze_track.py song.mp3 --out timing.json
  python analyze_track.py song.mp3 --cuts 3.6,5.7 \
    --scene-components world,split --scene-names 启航,离开 \
    --out timing.json --emit-ts src/generated/timeline.generated.ts
  python analyze_track.py song.mp3 --lrc lyrics.lrc --cues cues.json \
    --out timing.json --emit-ts src/generated/timeline.generated.ts

Requires: librosa, numpy, soundfile.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

import librosa
import numpy as np


def parse_lrc(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    pattern = re.compile(r"\[(\d+):(\d+(?:\.\d+)?)\]")
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        stamps = pattern.findall(line)
        if not stamps:
            continue
        text = pattern.sub("", line).strip()
        if text:
            for minutes, seconds_part in stamps:
                seconds = int(minutes) * 60 + float(seconds_part)
                rows.append({"t": round(seconds, 6), "text": text})
    return sorted(rows, key=lambda row: float(row["t"]))


def active_runs(
    times: np.ndarray,
    values: np.ndarray,
    threshold: float,
    merge_gap: float = 0.12,
) -> list[tuple[float, float]]:
    runs: list[tuple[float, float]] = []
    start: float | None = None
    for time, value in zip(times, values):
        active = value >= threshold
        if active and start is None:
            start = float(time)
        elif not active and start is not None:
            runs.append((start, float(time)))
            start = None
    if start is not None:
        runs.append((start, float(times[-1])))

    merged: list[tuple[float, float]] = []
    for run in runs:
        if merged and run[0] - merged[-1][1] <= merge_gap:
            merged[-1] = (merged[-1][0], run[1])
        else:
            merged.append(run)
    return merged


def estimate_body_end(
    times: np.ndarray,
    rms: np.ndarray,
    threshold: float,
    duration: float,
) -> tuple[float, str]:
    runs = active_runs(times, rms, threshold)
    if not runs:
        return round(duration, 4), "no-active-runs"
    last = runs[-1]
    if len(runs) >= 2:
        previous = runs[-2]
        isolated_tail = (
            last[1] - last[0] < 0.7
            and last[0] - previous[1] > 0.45
        )
        if isolated_tail:
            return round(min(previous[1], duration), 4), "trim-isolated-tail"
    if last[0] > 0.4 and last[1] - last[0] < 0.35:
        return round(last[1], 4), "last-short-event"
    return round(min(last[1], duration), 4), "last-active-run"


def nearest_beat_index(beats: np.ndarray, time: float) -> int:
    if len(beats) == 0:
        raise ValueError("cannot snap a cut without any beats")
    return int(np.argmin(np.abs(beats - time)))


def parse_csv(value: str) -> list[str]:
    return [part.strip() for part in value.split(",") if part.strip()]


def positive_float(value: str) -> float:
    parsed = float(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("value must be > 0")
    return parsed


def positive_int(value: str) -> int:
    parsed = int(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("value must be > 0")
    return parsed


def read_cues(path: Path | None) -> list[dict[str, Any]]:
    if path is None:
        return []
    payload = json.loads(path.read_text(encoding="utf-8"))
    cues = payload.get("cues", payload) if isinstance(payload, dict) else payload
    if not isinstance(cues, list):
        raise ValueError("cues file must be a list or an object with a 'cues' list")
    normalized: list[dict[str, Any]] = []
    for cue in cues:
        normalized.append(
            {
                "t": round(float(cue["t"]), 4),
                "file": str(cue["file"]),
                "volume": float(cue.get("volume", 0.06)),
                **(
                    {"durationSeconds": round(float(cue["durationSeconds"]), 4)}
                    if "durationSeconds" in cue
                    else {}
                ),
            }
        )
    return normalized


def emit_typescript(path: Path, timeline: dict[str, Any], import_path: str) -> None:
    body = json.dumps(timeline, ensure_ascii=False, indent=2)
    text = (
        "// AUTO-GENERATED by analyze_track.py. Do not edit by hand.\n"
        f'import type {{PaperCutTimeline}} from "{import_path}";\n\n'
        f"export const TIMELINE = {body} satisfies PaperCutTimeline;\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("audio", type=Path)
    parser.add_argument("--cuts", default="", help="comma-separated rough cut times")
    parser.add_argument("--lrc", type=Path)
    parser.add_argument("--cues", type=Path)
    parser.add_argument("--out", type=Path, default=Path("timing.json"))
    parser.add_argument("--emit-ts", type=Path)
    parser.add_argument("--timeline-import", default="../timeline")
    parser.add_argument("--title", default="Untitled paper-cut MV")
    parser.add_argument("--width", type=positive_int, default=1920)
    parser.add_argument("--height", type=positive_int, default=1080)
    parser.add_argument("--fps", type=positive_int, default=30)
    parser.add_argument("--audio-asset", default="audio/song.mp3")
    parser.add_argument("--no-audio", action="store_true")
    parser.add_argument("--body-end", type=positive_float)
    parser.add_argument("--fallback-bpm", type=positive_float, default=120.0)
    parser.add_argument("--scene-components", default="world")
    parser.add_argument("--scene-names", default="")
    parser.add_argument("--sr", type=positive_int, default=22050)
    args = parser.parse_args()

    y, sr = librosa.load(args.audio, sr=args.sr, mono=True)
    duration = len(y) / sr
    if duration <= 0:
        raise SystemExit("audio is empty")

    hop = 512
    rms = librosa.feature.rms(y=y, frame_length=2048, hop_length=hop)[0]
    rms_times = librosa.frames_to_time(np.arange(len(rms)), sr=sr, hop_length=hop)
    active = rms[rms > np.percentile(rms, 40)]
    threshold = float(np.percentile(active, 25) * 0.12) if len(active) else 1e-5
    body_end, body_method = estimate_body_end(rms_times, rms, threshold, duration)
    if args.body_end is not None:
        if args.body_end > duration:
            raise SystemExit(
                f"--body-end {args.body_end:.3f}s exceeds audio duration {duration:.3f}s"
            )
        body_end, body_method = min(args.body_end, duration), "cli"
    if body_end <= 0:
        raise SystemExit("musical body end must be > 0")

    tempo, beat_times = librosa.beat.beat_track(y=y, sr=sr, units="time", trim=False)
    detected_bpm = float(np.asarray(tempo).reshape(-1)[0])
    raw_detected_bpm = detected_bpm
    beat_times = np.asarray(
        [float(beat) for beat in beat_times if 0 <= float(beat) <= body_end + 0.001],
        dtype=float,
    )
    beat_grid_method = "librosa"
    if not np.isfinite(detected_bpm) or detected_bpm <= 0 or len(beat_times) == 0:
        detected_bpm = float(args.fallback_bpm)
        beat_times = np.arange(
            0.0,
            body_end + 1e-6,
            60.0 / detected_bpm,
            dtype=float,
        )
        beat_grid_method = "uniform-fallback"
    tempo_value = detected_bpm
    beat_seconds = 60.0 / tempo_value

    rough_cuts = [float(value) for value in args.cuts.split(",") if value.strip()]
    invalid_cuts = [cut for cut in rough_cuts if cut <= 0 or cut >= body_end]
    if invalid_cuts:
        raise SystemExit(
            f"cuts must be inside (0, {body_end:.3f}): {invalid_cuts}"
        )
    snapped_cuts: list[dict[str, Any]] = []
    scene_boundaries = [0.0]
    for cut in rough_cuts:
        index = nearest_beat_index(beat_times, cut)
        snapped = round(float(beat_times[index]), 4)
        snapped_cuts.append(
            {
                "requested": cut,
                "snapped": snapped,
                "nearest_beat_index": index,
                "delta_ms": round((snapped - cut) * 1000, 1),
            }
        )
        if 0 < snapped < body_end:
            scene_boundaries.append(snapped)
    scene_boundaries.append(body_end)
    scene_boundaries = sorted(set(round(value, 4) for value in scene_boundaries))

    components = parse_csv(args.scene_components)
    names = parse_csv(args.scene_names)
    if not components:
        components = ["world"]
    if len(components) == 1 and len(scene_boundaries) > 2:
        components = components * (len(scene_boundaries) - 1)
    if len(components) != len(scene_boundaries) - 1:
        raise SystemExit(
            f"scene-components has {len(components)} entries but cuts produce "
            f"{len(scene_boundaries) - 1} scenes"
        )

    scenes = []
    for index, (start, end) in enumerate(zip(scene_boundaries, scene_boundaries[1:])):
        name = names[index] if index < len(names) else f"Scene {index + 1:02d}"
        scenes.append(
            {
                "id": f"{index + 1:02d}-{components[index]}",
                "name": name,
                "start": start,
                "end": end,
                "component": components[index],
            }
        )

    lyric_rows = parse_lrc(args.lrc) if args.lrc else []
    lyrics = []
    for index, row in enumerate(lyric_rows):
        actual_start = float(row["t"])
        if actual_start < 0 or actual_start >= body_end:
            continue
        start = actual_start
        nearest = nearest_beat_index(beat_times, start)
        nearest_time = float(beat_times[nearest])
        end = (
            min(float(lyric_rows[index + 1]["t"]), body_end)
            if index + 1 < len(lyric_rows)
            else body_end
        )
        if end > start:
            lyrics.append(
                {
                    "start": round(start, 4),
                    "end": round(end, 4),
                    "text": str(row["text"]),
                    "nearestBeat": round(nearest_time, 4),
                    "beatIndex": nearest,
                    "beatDeltaMs": round((nearest_time - start) * 1000, 1),
                }
            )

    beats = [
        round(float(beat), 4)
        for beat in beat_times
        if 0 <= float(beat) <= body_end + 0.001
    ]
    timeline = {
        "meta": {
            "title": args.title,
            "width": args.width,
            "height": args.height,
            "fps": args.fps,
            "duration": round(body_end, 4),
            "musicBodyEnd": round(body_end, 4),
            "audio": None if args.no_audio else args.audio_asset,
            "bgmVolume": 0.9,
            "bpm": round(tempo_value, 4),
        },
        "beats": beats,
        "scenes": scenes,
        "lyrics": lyrics,
        "cues": read_cues(args.cues),
    }

    timing = {
        "audio": str(args.audio),
        "duration": round(duration, 4),
        "musical_body_end": round(body_end, 4),
        "body_end_method": body_method,
        "target_width": args.width,
        "target_height": args.height,
        "fps": args.fps,
        "bpm": round(tempo_value, 4),
        "detected_bpm": (
            round(raw_detected_bpm, 4)
            if beat_grid_method == "librosa"
            else None
        ),
        "beat_grid_method": beat_grid_method,
        "beat_seconds": round(beat_seconds, 6),
        "offset": round(float(beat_times[0]), 4) if len(beat_times) else None,
        "beat_count": len(beats),
        "beats": beats,
        "half_beats": [
            round(float((a + b) / 2), 4) for a, b in zip(beats, beats[1:])
        ],
        "silence_threshold": round(threshold, 6),
        "snapped_cuts": snapped_cuts,
        "scenes": scenes,
        "lyrics": lyrics,
    }

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps(timing, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    if args.emit_ts:
        emit_typescript(args.emit_ts, timeline, args.timeline_import)
    print(json.dumps(timing, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
