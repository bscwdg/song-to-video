#!/usr/bin/env python3
"""Turn an approved storyboard + measured timing into Remotion timeline data.

Example:
  python scripts/storyboard_to_timeline.py timing.json storyboard.json \
    --out-ts src/generated/timeline.generated.ts
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from validate_storyboard import validate_storyboard


def nearest_beat(beats: list[float], time: float) -> tuple[int, float]:
    if not beats:
        return (0, 0.0)
    index = min(range(len(beats)), key=lambda i: abs(float(beats[i]) - time))
    return (index, float(beats[index]))


def build_timeline(
    timing: dict[str, Any],
    storyboard: dict[str, Any],
    *,
    audio_asset: str = "audio/song.mp3",
    cues: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    errors, warnings = validate_storyboard(storyboard)
    if errors:
        raise ValueError("invalid storyboard:\n- " + "\n- ".join(errors))
    for warning in warnings:
        print(f"WARN · {warning}")

    body_end = float(timing.get("musical_body_end", timing.get("duration", 0)))
    storyboard_duration = float(storyboard["duration"])
    if abs(body_end - storyboard_duration) > 0.15:
        raise ValueError(
            f"storyboard duration {storyboard_duration:.3f}s does not match "
            f"timing musical_body_end {body_end:.3f}s"
        )

    beats = [round(float(beat), 4) for beat in timing.get("beats", [])]
    width = int(timing.get("target_width", 1920))
    height = int(timing.get("target_height", 1080))
    fps = int(storyboard.get("fps", timing.get("fps", 30)))

    scenes: list[dict[str, Any]] = []
    lyrics: list[dict[str, Any]] = []
    for shot in storyboard["shots"]:
        archetype = str(shot["scene"]["archetype"])
        scenes.append(
            {
                "id": f"{shot['id']}-{archetype}",
                "name": str(shot["intent"]),
                "start": round(float(shot["start"]), 4),
                "end": round(float(shot["end"]), 4),
                "component": archetype,
            }
        )
        for line in shot.get("lyrics", []):
            start = round(float(line["start"]), 4)
            index, snapped = nearest_beat(beats, start)
            lyrics.append(
                {
                    "start": start,
                    "end": round(float(line["end"]), 4),
                    "text": str(line["text"]),
                    "nearestBeat": round(snapped, 4),
                    "beatIndex": index,
                    "beatDeltaMs": round((snapped - start) * 1000, 1),
                }
            )

    return {
        "meta": {
            "title": str(storyboard["title"]),
            "width": width,
            "height": height,
            "fps": fps,
            "duration": round(storyboard_duration, 4),
            "musicBodyEnd": round(body_end, 4),
            "audio": audio_asset,
            "bgmVolume": 0.9,
            "bpm": round(float(timing.get("bpm", 0)), 4),
        },
        "beats": beats,
        "scenes": scenes,
        "lyrics": lyrics,
        "cues": cues or [],
    }


def emit_typescript(
    path: Path,
    timeline: dict[str, Any],
    import_path: str,
) -> None:
    body = json.dumps(timeline, ensure_ascii=False, indent=2)
    text = (
        "// AUTO-GENERATED by storyboard_to_timeline.py. Do not edit by hand.\n"
        f'import type {{PaperCutTimeline}} from "{import_path}";\n\n'
        f"export const TIMELINE = {body} satisfies PaperCutTimeline;\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("timing", type=Path)
    parser.add_argument("storyboard", type=Path)
    parser.add_argument("--out-ts", type=Path, required=True)
    parser.add_argument("--timeline-import", default="../timeline")
    parser.add_argument("--audio-asset", default="audio/song.mp3")
    parser.add_argument("--cues", type=Path)
    args = parser.parse_args()

    timing = json.loads(args.timing.read_text(encoding="utf-8"))
    storyboard = json.loads(args.storyboard.read_text(encoding="utf-8"))
    cues_payload = None
    if args.cues:
        raw = json.loads(args.cues.read_text(encoding="utf-8"))
        cues_payload = raw.get("cues", raw) if isinstance(raw, dict) else raw

    timeline = build_timeline(
        timing,
        storyboard,
        audio_asset=args.audio_asset,
        cues=cues_payload,
    )
    emit_typescript(args.out_ts, timeline, args.timeline_import)
    print(
        json.dumps(
            {
                "output": str(args.out_ts),
                "shots": len(timeline["scenes"]),
                "lyrics": len(timeline["lyrics"]),
                "duration": timeline["meta"]["duration"],
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
